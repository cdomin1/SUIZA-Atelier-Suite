fn key_for_char(c: char) -> Option<Key> {
    Some(match c {
        'a' => Key::A,
        'b' => Key::B,
        'c' => Key::C,
        'd' => Key::D,
        'e' => Key::E,
        'f' => Key::F,
        'g' => Key::G,
        'h' => Key::H,
        'i' => Key::I,
        'j' => Key::J,
        'k' => Key::K,
        'l' => Key::L,
        'm' => Key::M,
        'n' => Key::N,
        'o' => Key::O,
        'p' => Key::P,
        'q' => Key::Q,
        'r' => Key::R,
        's' => Key::S,
        't' => Key::T,
        'u' => Key::U,
        'v' => Key::V,
        'w' => Key::W,
        'x' => Key::X,
        'y' => Key::Y,
        'z' => Key::Z,
        '0' => Key::Num0,
        '1' => Key::Num1,
        '2' => Key::Num2,
        '3' => Key::Num3,
        '4' => Key::Num4,
        '5' => Key::Num5,
        '6' => Key::Num6,
        '7' => Key::Num7,
        '8' => Key::Num8,
        '9' => Key::Num9,
        '=' | '+' => Key::Equals,
        '-' => Key::Minus,
        '[' => Key::OpenBracket,
        ']' => Key::CloseBracket,
        ';' | ':' => Key::Semicolon,
        '\'' | '"' => return None, // egui has no quote key
        '\\' => Key::Backslash,
        _ => return None,
    })
}

fn shortcut_key(key: &str) -> Option<Key> {
    match key {
        "Delete" => Some(Key::Delete),
        "Backspace" => Some(Key::Backspace),
        "Enter" => Some(Key::Enter),
        "Escape" | "Esc" => Some(Key::Escape),
        "Space" => Some(Key::Space),
        "Tab" => Some(Key::Tab),
        other => other
            .chars()
            .next()
            .and_then(|c| key_for_char(c.to_ascii_lowercase())),
    }
}

/// Returns ids of shortcuts triggered this frame. `command` covers Ctrl on
/// Linux/Windows and Cmd on macOS.
pub fn triggered(input: &InputState, shortcuts: &[KeyboardShortcut]) -> Vec<String> {
    let mut hits = Vec::new();
    for sc in shortcuts {
        let Some(key) = shortcut_key(&sc.key) else {
            continue;
        };
        let mods_ok = input.modifiers.command == sc.ctrl
            && input.modifiers.shift == sc.shift
            && input.modifiers.alt == sc.alt;
        if mods_ok && input.key_pressed(key) {
            hits.push(sc.id.clone());
        }
    }
    hits
}
